"""Transform that exposes prompts as tools.

This transform generates tools for listing and getting prompts, enabling
clients that only support tools to access prompt functionality.

The generated tools route through `ctx.fastmcp` at runtime, so all server
middleware (auth, visibility, rate limiting, etc.) applies to prompt
operations exactly as it would for direct `prompts/get` calls.

Example:
    ```python
    from fastmcp import FastMCP
    from fastmcp.server.transforms import PromptsAsTools

    mcp = FastMCP("Server")
    mcp.add_transform(PromptsAsTools(mcp))
    # Now has list_prompts and get_prompt tools
    ```
"""

from __future__ import annotations

import contextlib
import json
from collections.abc import Sequence
from typing import TYPE_CHECKING, Annotated, Any

from mcp_types import InputRequiredResult, TextContent

from fastmcp.prompts.base import InputRequiredPromptResult
from fastmcp.server.dependencies import get_context
from fastmcp.server.transforms import GetToolNext, Transform
from fastmcp.tools.base import Tool
from fastmcp.utilities.versions import VersionSpec, dedupe_with_versions

if TYPE_CHECKING:
    from fastmcp.server.providers.base import Provider


class PromptsAsTools(Transform):
    """Transform that adds tools for listing and getting prompts.

    Generates two tools:
    - `list_prompts`: Lists all prompts
    - `get_prompt`: Gets a specific prompt with optional arguments

    The generated tools route through the server at runtime, so auth,
    middleware, and visibility apply automatically.

    This transform should be applied to a FastMCP server instance, not
    a raw Provider, because the generated tools need the server's
    middleware chain for auth and visibility filtering.

    Example:
        ```python
        mcp = FastMCP("Server")
        mcp.add_transform(PromptsAsTools(mcp))
        # Now has list_prompts and get_prompt tools
        ```
    """

    def __init__(self, provider: Provider) -> None:
        from fastmcp.server.server import FastMCP

        if not isinstance(provider, FastMCP):
            raise TypeError(
                "PromptsAsTools requires a FastMCP server instance, not a"
                f" {type(provider).__name__}. The generated tools route through"
                " the server's middleware chain at runtime for auth and"
                " visibility. Pass your FastMCP server: PromptsAsTools(mcp)"
            )
        self._provider = provider

    def __repr__(self) -> str:
        return f"PromptsAsTools({self._provider!r})"

    def _is_adapter_generated_tool(self, tool: Tool) -> bool:
        """Check if tool was generated by another PromptsAsTools adapter."""
        curr: Any = tool
        while curr is not None:
            meta = (
                curr.get_meta()
                if hasattr(curr, "get_meta")
                else getattr(curr, "meta", None)
            )
            if (
                isinstance(meta, dict)
                and meta.get("fastmcp:adapter") == "PromptsAsTools"
            ):
                return True
            curr = getattr(curr, "parent_tool", None)

        server = getattr(tool, "_server", None)
        if server is not None:
            server_transforms = getattr(server, "transforms", [])
            if any(type(t).__name__ == "PromptsAsTools" for t in server_transforms):
                if tool.name in ("list_prompts", "get_prompt"):
                    return True

        if tool.name == "get_prompt":
            desc = getattr(tool, "description", "") or ""
            if desc.startswith(
                "Get a prompt by name with optional arguments."
            ) and "name" in getattr(tool, "parameters", {}).get("properties", {}):
                return True
        elif tool.name == "list_prompts":
            desc = getattr(tool, "description", "") or ""
            if desc.startswith("List all available prompts."):
                return True

        return False

    async def _is_tool_finally_enabled(self, tool: Tool) -> bool:
        """Check if tool is enabled and will not be disabled by subsequent server or session visibility transforms."""
        from fastmcp.server.transforms.visibility import (
            Visibility,
            apply_session_transforms,
            is_enabled,
        )

        if not is_enabled(tool):
            return False

        top_transforms = getattr(self._provider, "transforms", [])
        try:
            idx = top_transforms.index(self)
            subsequent = top_transforms[idx + 1 :]
        except ValueError:
            subsequent = []

        current_tool = tool
        for t in subsequent:
            if isinstance(t, Visibility):
                current_tool = t._mark_component(current_tool)

        session_tools = await apply_session_transforms([current_tool])
        return is_enabled(session_tools[0])

    async def _is_tool_authorized(self, tool: Tool) -> bool:
        """Check if tool is authorized by component auth and server AuthMiddleware."""
        from fastmcp.exceptions import AuthorizationError
        from fastmcp.server.auth import AuthContext, run_auth_checks
        from fastmcp.server.context import _current_transport
        from fastmcp.server.dependencies import get_access_token
        from fastmcp.server.middleware.authorization import AuthMiddleware
        from fastmcp.server.server import _component_auth_allows

        try:
            if not await _component_auth_allows(tool):
                return False
        except Exception:
            return False

        if _current_transport.get() == "stdio":
            return True

        middleware = getattr(self._provider, "middleware", None)
        if isinstance(middleware, list):
            token = get_access_token()
            ctx = AuthContext(token=token, component=tool)
            for mw in middleware:
                if isinstance(mw, AuthMiddleware):
                    try:
                        if not await run_auth_checks(mw.auth, ctx):
                            return False
                    except AuthorizationError:
                        return False
                    except Exception:
                        return False
        return True

    async def _is_tool_hidden_by_search(self, tool: Tool) -> bool:
        """Check if a specific tool is hidden by search, catalog transforms, or child middleware."""
        from fastmcp.server.transforms.catalog import CatalogTransform
        from fastmcp.tools.base import Tool as ToolCls

        top_transforms = getattr(self._provider, "transforms", [])
        try:
            idx = top_transforms.index(self)
            preceding = top_transforms[:idx]
        except ValueError:
            preceding = top_transforms

        from fastmcp.server.transforms.namespace import Namespace

        def _reverse_name_through_provider(provider: Any, name: str) -> str:
            current = name

            def _apply_reverse_transform(t: Any, n: str) -> str:
                if isinstance(t, Namespace):
                    rev = t._reverse_name(n)
                    return rev if rev is not None else n
                name_reverse = getattr(t, "_name_reverse", None)
                if isinstance(name_reverse, dict) and n in name_reverse:
                    return name_reverse[n]
                return n

            single_t = getattr(provider, "_transform", None)
            if single_t is not None:
                current = _apply_reverse_transform(single_t, current)

            for t in reversed(getattr(provider, "transforms", [])):
                current = _apply_reverse_transform(t, current)

            prov_server = getattr(provider, "server", None)
            if prov_server is not None:
                for t in reversed(getattr(prov_server, "transforms", [])):
                    current = _apply_reverse_transform(t, current)

            return current

        async def _find_tool_provider_chain(target_tool: Tool) -> list[Any]:
            candidate_tools = [target_tool]
            curr = target_tool
            while getattr(curr, "parent_tool", None) is not None:
                curr = curr.parent_tool
                candidate_tools.append(curr)

            server_attrs = [
                getattr(t, "_server", None)
                for t in candidate_tools
                if getattr(t, "_server", None) is not None
            ]
            provider_attrs = [
                getattr(t, "_provider", None)
                for t in candidate_tools
                if getattr(t, "_provider", None) is not None
            ]

            def _find_by_identity(providers_list: Sequence[Any]) -> list[Any] | None:
                for p in providers_list:
                    if any(getattr(p, "server", None) is s for s in server_attrs):
                        return [p]
                    inner = getattr(p, "_inner", None)
                    if any(getattr(inner, "server", None) is s for s in server_attrs):
                        return [p]
                    if any(
                        p is pr or getattr(p, "_inner", None) is pr
                        for pr in provider_attrs
                    ):
                        return [p]
                    sub = getattr(p, "providers", [])
                    found = _find_by_identity(sub)
                    if found is not None:
                        return [p, *found]
                return None

            if server_attrs or provider_attrs:
                by_id = _find_by_identity(getattr(self._provider, "providers", []))
                if by_id is not None:
                    return by_id

            def _find_by_tool_object(
                providers_list: Sequence[Any],
            ) -> list[Any] | None:
                for p in providers_list:
                    comps = getattr(p, "_components", None)
                    if isinstance(comps, dict) and any(
                        isinstance(c, ToolCls)
                        and any(c is ct for ct in candidate_tools)
                        for c in comps.values()
                    ):
                        return [p]
                    tools_dict = getattr(p, "_tools", None)
                    if isinstance(tools_dict, dict) and any(
                        isinstance(t, ToolCls)
                        and any(t is ct for ct in candidate_tools)
                        for t in tools_dict.values()
                    ):
                        return [p]
                    sub = getattr(p, "providers", [])
                    if sub:
                        found = _find_by_tool_object(sub)
                        if found is not None:
                            return [p, *found]
                return None

            by_tool_obj = _find_by_tool_object(getattr(self._provider, "providers", []))
            if by_tool_obj is not None:
                return by_tool_obj

            local_prov = getattr(self._provider, "local_provider", None)
            if local_prov is not None:
                comps = getattr(local_prov, "_components", None)
                if isinstance(comps, dict) and any(
                    isinstance(c, ToolCls) and any(c is ct for ct in candidate_tools)
                    for c in comps.values()
                ):
                    return [local_prov]
                tools_dict = getattr(local_prov, "_tools", None)
                if isinstance(tools_dict, dict) and any(
                    isinstance(t, ToolCls) and any(t is ct for ct in candidate_tools)
                    for t in tools_dict.values()
                ):
                    return [local_prov]

            async def _search_providers(
                providers_list: Sequence[Any], name: str
            ) -> list[Any] | None:
                for p in providers_list:
                    local_name = _reverse_name_through_provider(p, name)
                    candidate_names = {local_name, *(t.name for t in candidate_tools)}

                    comps = getattr(p, "_components", None)
                    if isinstance(comps, dict) and any(
                        isinstance(c, ToolCls)
                        and any(
                            c is ct
                            or (
                                getattr(c, "key", None) is not None
                                and getattr(c, "key", None) == getattr(ct, "key", None)
                            )
                            or (
                                getattr(c, "name", None) in candidate_names
                                and getattr(c, "version", None)
                                == getattr(ct, "version", None)
                            )
                            for ct in candidate_tools
                        )
                        for c in comps.values()
                    ):
                        return [p]

                    tools_dict = getattr(p, "_tools", None)
                    if isinstance(tools_dict, dict) and any(
                        isinstance(t, ToolCls)
                        and any(
                            t is ct
                            or (
                                getattr(t, "key", None) is not None
                                and getattr(t, "key", None) == getattr(ct, "key", None)
                            )
                            or (
                                getattr(t, "name", None) in candidate_names
                                and getattr(t, "version", None)
                                == getattr(ct, "version", None)
                            )
                            for ct in candidate_tools
                        )
                        for t in tools_dict.values()
                    ):
                        return [p]

                    sub = getattr(p, "providers", [])
                    if sub:
                        found = await _search_providers(sub, local_name)
                        if found is not None:
                            return [p, *found]

                    get_tool_fn = getattr(p, "_get_tool", None)
                    if callable(get_tool_fn):
                        probe_names = [local_name]
                        for ct in candidate_tools:
                            if ct.name not in probe_names:
                                probe_names.append(ct.name)
                        for probe_name in probe_names:
                            with contextlib.suppress(Exception):
                                version_arg = (
                                    VersionSpec(eq=target_tool.version)
                                    if target_tool.version is not None
                                    else None
                                )
                                p_tool = await get_tool_fn(
                                    probe_name, version=version_arg
                                )
                                if p_tool is not None and any(
                                    p_tool is ct
                                    or (
                                        getattr(p_tool, "key", None) is not None
                                        and getattr(p_tool, "key", None)
                                        == getattr(ct, "key", None)
                                    )
                                    or (
                                        p_tool.name in candidate_names
                                        and p_tool.version
                                        == getattr(ct, "version", None)
                                    )
                                    for ct in candidate_tools
                                ):
                                    return [p]
                return None

            found = await _search_providers(
                getattr(self._provider, "providers", []), target_tool.name
            )
            if found is not None:
                return found

            local_prov = getattr(self._provider, "local_provider", None)
            if local_prov is not None:
                comps = getattr(local_prov, "_components", None)
                if isinstance(comps, dict) and any(
                    isinstance(c, ToolCls)
                    and any(
                        c is ct
                        or (
                            getattr(c, "key", None) is not None
                            and getattr(c, "key", None) == getattr(ct, "key", None)
                        )
                        or (
                            getattr(c, "name", None)
                            in {ct.name for ct in candidate_tools}
                            and getattr(c, "version", None)
                            == getattr(ct, "version", None)
                        )
                        for ct in candidate_tools
                    )
                    for c in comps.values()
                ):
                    return [local_prov]

            fallback = getattr(self._provider, "local_provider", None) or self._provider
            return [fallback]

        chain = await _find_tool_provider_chain(tool)
        owner = chain[-1] if chain else None
        owner_server = getattr(owner, "server", None)

        candidate_tools = [tool]
        curr = tool
        while getattr(curr, "parent_tool", None) is not None:
            curr = curr.parent_tool
            candidate_tools.append(curr)

        def _is_tool_listing_transform(t: Any) -> bool:
            if isinstance(t, CatalogTransform):
                return True
            list_tool_method = getattr(t, "list_tools", None)
            if not callable(list_tool_method):
                return False
            underlying = getattr(list_tool_method, "__func__", list_tool_method)
            return underlying is not Transform.list_tools

        has_chain_transforms = any(getattr(p, "transforms", None) for p in chain)
        has_owner_server_transforms = bool(
            owner_server and getattr(owner_server, "transforms", [])
        )
        has_owner_server_middleware = bool(
            owner_server and getattr(owner_server, "middleware", None)
        )
        has_preceding_listing = any(_is_tool_listing_transform(t) for t in preceding)

        if (
            not has_chain_transforms
            and not has_owner_server_transforms
            and not has_owner_server_middleware
            and not has_preceding_listing
        ):
            # Fast path: No listing transforms or child middleware can hide this tool.
            # Avoids querying unrelated providers (e.g. ProxyProvider over network).
            return False

        # Load tool candidate sequence from the owning provider (or local provider if unowned)
        target_provider = (
            owner or getattr(self._provider, "local_provider", None) or self._provider
        )
        list_fn = getattr(target_provider, "_list_tools", None)
        if callable(list_fn):
            try:
                raw = await list_fn()
                current_tools = list(raw) if isinstance(raw, Sequence) else [tool]
            except Exception:
                current_tools = [tool]
        else:
            current_tools = [tool]

        for p in reversed(chain):
            for t in getattr(p, "transforms", []):
                try:
                    current_tools = list(await t.list_tools(current_tools))
                except Exception:
                    if type(t).__name__ == "CodeMode":
                        return True

        local_prov = getattr(self._provider, "local_provider", None)
        if owner is not None and (
            owner is not local_prov or getattr(local_prov, "transforms", None)
        ):
            pre_name = tool.name
            for t in reversed(preceding):
                if isinstance(t, Namespace):
                    rev = t._reverse_name(pre_name)
                    if rev is not None:
                        pre_name = rev
                name_reverse = getattr(t, "_name_reverse", None)
                if isinstance(name_reverse, dict) and pre_name in name_reverse:
                    pre_name = name_reverse[pre_name]

            if not any(
                isinstance(x, ToolCls)
                and (
                    x is tool
                    or getattr(x, "parent_tool", None) is tool
                    or getattr(tool, "parent_tool", None) is x
                    or (x.name == pre_name and x.version == tool.version)
                    or (
                        pre_name == tool.name
                        and x.key is not None
                        and x.key == tool.key
                    )
                )
                for x in current_tools
            ):
                return True

        # Evaluate preceding transforms on self._provider (e.g. Namespace, CatalogTransform, custom Transform)
        for t in preceding:
            try:
                current_tools = list(await t.list_tools(current_tools))
            except Exception:
                if type(t).__name__ == "CodeMode":
                    return True

        return not any(
            isinstance(x, ToolCls)
            and (
                x is tool
                or getattr(x, "parent_tool", None) is tool
                or getattr(tool, "parent_tool", None) is x
                or (x.key is not None and x.key == tool.key)
                or (x.name == tool.name and x.version == tool.version)
            )
            for x in current_tools
        )

    async def list_tools(self, tools: Sequence[Tool]) -> Sequence[Tool]:
        """Add prompt tools to the tool list."""
        list_tool = self._make_list_prompts_tool()
        get_tool = self._make_get_prompt_tool()
        candidate_keys = {list_tool.key, get_tool.key}

        filtered_tools: list[Tool] = []
        user_override_keys: set[str] = set()

        for t in tools:
            if t.key in candidate_keys:
                if self._is_adapter_generated_tool(t):
                    continue
                if not await self._is_tool_finally_enabled(t):
                    continue
                if await self._is_tool_authorized(t):
                    user_override_keys.add(t.key)
                filtered_tools.append(t)
            else:
                filtered_tools.append(t)

        synthetic: list[Tool] = []
        if list_tool.key not in user_override_keys:
            synthetic.append(list_tool)
        if get_tool.key not in user_override_keys:
            synthetic.append(get_tool)
        return [*filtered_tools, *synthetic]

    async def get_tool(
        self, name: str, call_next: GetToolNext, *, version: VersionSpec | None = None
    ) -> Tool | None:
        """Get a tool by name, including generated prompt tools."""
        if name not in ("list_prompts", "get_prompt"):
            return await call_next(name, version=version)

        syn = (
            self._make_list_prompts_tool()
            if name == "list_prompts"
            else self._make_get_prompt_tool()
        )
        syn_matches = version is None or version.matches(syn.version)

        existing = await call_next(name, version=version)
        if (
            existing is not None
            and not self._is_adapter_generated_tool(existing)
            and await self._is_tool_finally_enabled(existing)
            and await self._is_tool_authorized(existing)
        ):
            if syn_matches and await self._is_tool_hidden_by_search(existing):
                return syn
            return existing

        if syn_matches:
            return syn

        return None

    def _make_list_prompts_tool(self) -> Tool:
        """Create the list_prompts tool."""

        async def list_prompts() -> str:
            """List all available prompts.

            Returns JSON with prompt metadata including name, description,
            and optional arguments.
            """
            ctx = get_context()
            prompts = dedupe_with_versions(
                await ctx.fastmcp.list_prompts(), lambda p: p.name
            )

            result: list[dict[str, Any]] = []
            for p in prompts:
                result.append(  # noqa: PERF401
                    {
                        "name": p.name,
                        "description": p.description,
                        "arguments": [
                            {
                                "name": arg.name,
                                "description": arg.description,
                                "required": arg.required,
                            }
                            for arg in (p.arguments or [])
                        ],
                    }
                )

            return json.dumps(result, indent=2)

        return Tool.from_function(
            fn=list_prompts,
            meta={"fastmcp:adapter": "PromptsAsTools"},
        )

    def _make_get_prompt_tool(self) -> Tool:
        """Create the get_prompt tool."""

        async def get_prompt(
            name: Annotated[str, "The name of the prompt to get"],
            arguments: Annotated[
                dict[str, Any] | None,
                "Optional arguments for the prompt",
            ] = None,
        ) -> str | InputRequiredResult:
            """Get a prompt by name with optional arguments.

            Returns the rendered prompt as JSON with a messages array.
            Arguments should be provided as a dict mapping argument names
            to values.
            """
            ctx = get_context()
            result = await ctx.fastmcp.render_prompt(name, arguments=arguments or {})
            if isinstance(result, InputRequiredPromptResult):
                return result.input_required
            return _format_prompt_result(result)

        return Tool.from_function(
            fn=get_prompt,
            meta={"fastmcp:adapter": "PromptsAsTools"},
        )


def _format_prompt_result(result: Any) -> str:
    """Format PromptResult for tool output.

    Returns JSON with the messages array. Preserves embedded resources
    as structured JSON objects.
    """
    messages = []
    for msg in result.messages:
        if isinstance(msg.content, TextContent):
            content = msg.content.text
        else:
            content = msg.content.model_dump(
                mode="json", by_alias=True, exclude_none=True
            )

        messages.append(
            {
                "role": msg.role,
                "content": content,
            }
        )

    return json.dumps({"messages": messages}, indent=2)
